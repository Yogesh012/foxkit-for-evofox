pub fn chip_8_dpi(value: u16) -> Option<u16> {
    CHIP_8.iter().find(|entry| entry.0 == value).map(|entry| entry.1)
}

pub fn chip_8_value(dpi: u16) -> Option<u16> {
    CHIP_8.iter().find(|entry| entry.1 == dpi).map(|entry| entry.0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dpi_converts_both_ways() {
        assert_eq!(chip_8_value(800), Some(9));
        assert_eq!(chip_8_value(12000), Some(143));
        assert_eq!(chip_8_value(850), None);
    }

    #[test]
    fn values_confirmed_on_the_mouse_display() {
        assert_eq!(chip_8_dpi(9), Some(800));
        assert_eq!(chip_8_dpi(18), Some(1600));
        assert_eq!(chip_8_dpi(38), Some(3200));
    }

    #[test]
    fn unknown_value_has_no_label() {
        assert_eq!(chip_8_dpi(1), None);
    }
}
